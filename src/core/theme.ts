/**
 * 주제 선율 (D 장조).
 *  - '처음 돌아온 색' (처음으로 이웃을 깨우는 순간) 에서 앞의 다섯 음이 처음 들린다.
 *  - 여백의 땅 마지막 다리에서, 깨운 이웃이 하나씩 나타날 때마다 한 음씩 이어져 선율이 완성된다.
 * 반음 단위, 0 = D4. 화음은 네 음마다 D – Bm – G – A 로 돈다.
 */
export const MOTIF = [0, 4, 7, 9, 7];

export const MELODY = [
  // D        Bm
  0, 4, 7, 9, 7, 4, 2, 4,
  // G        A
  9, 7, 5, 7, 9, 11, 14, 11,
  // D        Bm
  12, 9, 7, 4, 9, 7, 4, 2,
  // G        A → D
  5, 4, 2, 4, 7, 11, 9, 12,
];

/** 네 음마다 바뀌는 화음 (낮게 펼친 소리) */
export const CHORDS: number[][] = [
  [-12, -5, 0, 4], // D
  [-15, -8, -3, 2], // Bm
  [-19, -7, -3, 0], // G
  [-17, -5, -1, 2], // A
];

export const chordFor = (i: number) => CHORDS[Math.floor(i / 4) % CHORDS.length];
